import pytest

from config import Settings
from modules.ai_generator import GenerationResult
from modules.demo import DEMO_LABEL, DEMO_SAMPLE_NAMES, get_demo_result
from modules.errors import InvalidURLError, MissingAPIKeyError, UnsafeURLError
from modules.pipeline import OpenerPipeline
from modules.validator import validate_opener
from tests.conftest import SAMPLE_HTML, FakeResponse, FakeSession, make_resolver


def settings(key="k" * 10):
    return Settings(api_key=key, model="m", max_content_chars=6000, request_timeout=5, cache_ttl_seconds=3600,
                    max_retries=1, price_input_per_1m=0.25, price_output_per_1m=1.5)


class FakeGenerator:
    model = "fake-model"

    def __init__(self):
        self.calls = 0

    def generate(self, data):
        self.calls += 1
        return GenerationResult(["a" * 30, "b" * 30, "c" * 30], self.model, 100, 20)


def build(generator=None, responses=None):
    session = FakeSession(*(responses or [FakeResponse(SAMPLE_HTML) for _ in range(3)]))
    pipeline = OpenerPipeline(settings(), generator=generator or FakeGenerator(), session=session,
                              resolver=make_resolver())
    return pipeline, session


def test_full_flow_reports_steps():
    pipeline, _ = build()
    steps = []
    result = pipeline.run("acme-routes.com", on_step=steps.append)
    assert result.website.title.startswith("Acme") and len(result.opener.lines) == 3
    assert steps[0] == "Validating URL" and any("Generating" in s for s in steps)


def test_repeat_url_uses_cache_and_skips_fetch_and_ai():
    generator = FakeGenerator()
    pipeline, session = build(generator)
    pipeline.run("https://acme-routes.com")
    second = pipeline.run("acme-routes.com")
    assert len(session.requested) == 1 and generator.calls == 1
    assert second.website_from_cache and second.opener_from_cache


def test_generate_again_calls_ai_but_reuses_extraction():
    generator = FakeGenerator()
    pipeline, session = build(generator)
    pipeline.run("https://acme-routes.com")
    pipeline.run("https://acme-routes.com", force_regenerate=True)
    assert len(session.requested) == 1 and generator.calls == 2


def test_missing_key_fails_before_any_network_request():
    session = FakeSession(FakeResponse(SAMPLE_HTML))
    pipeline = OpenerPipeline(settings(key=""), session=session, resolver=make_resolver())
    with pytest.raises(MissingAPIKeyError):
        pipeline.run("https://acme-routes.com")
    assert session.requested == []


def test_invalid_and_private_urls_rejected_before_fetch():
    pipeline, session = build()
    with pytest.raises(InvalidURLError):
        pipeline.run("")
    with pytest.raises(UnsafeURLError):
        pipeline.run("http://192.168.0.10")
    assert session.requested == []



@pytest.mark.parametrize("name", DEMO_SAMPLE_NAMES)
def test_demo_samples_are_valid_three_line_openers(name):
    data, result = get_demo_result(name)
    assert validate_opener("\n".join(result.lines)) == result.lines
    assert data.total_chars >= 200 and data.url.endswith(".example/")
    assert result.model.startswith("demo")


